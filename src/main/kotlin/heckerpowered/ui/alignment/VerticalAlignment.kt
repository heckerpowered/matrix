package heckerpowered.ui.alignment

/**
 * The vertical alignment of an element.
 */
enum class VerticalAlignment {
    /**
     * Align the element to the top of its ancestor element.
     */
    TOP,

    /**
     * Align the element to the center of its ancestor element.
     */
    CENTER,

    /**
     * Align the element to the bottom of its ancestor element.
     */
    BOTTOM,

    /**
     * Stretch the element to fill the entire height of its ancestor element.
     */
    STRETCH
}
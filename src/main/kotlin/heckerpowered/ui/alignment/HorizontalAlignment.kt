package heckerpowered.ui.alignment

/**
 * Represents the horizontal alignment of an element.
 */
enum class HorizontalAlignment {
    /**
     * Aligns the element to the left.
     */
    LEFT,

    /**
     * Aligns the element to the center.
     */
    CENTER,

    /**
     * Aligns the element to the right.
     */
    RIGHT,

    /**
     * Stretches the element to fill the available width.
     */
    STRETCH
}